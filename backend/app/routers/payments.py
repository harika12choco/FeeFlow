"""Payment link, simulated payment flow and receipts."""
from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from ..database import get_db
from ..deps import authorize_student_access, get_current_user
from ..models import Instalment, Payment, Student, User
from ..schemas import PaymentConfirmRequest, PaymentInitiateRequest
from ..serializers import payment_out
from ..services.ledger import instalment_state
from ..services.payments import confirm_payment, initiate_payment

router = APIRouter(prefix="/payments", tags=["payments"])


def _load_instalment(db: Session, instalment_id: int) -> Instalment:
    inst = db.get(Instalment, instalment_id)
    if not inst:
        raise HTTPException(status_code=404, detail="Instalment not found")
    return inst


@router.get("/link/{instalment_id}")
def payment_link(
    instalment_id: int,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict:
    """Data behind the per-instalment 'payment link'."""
    inst = _load_instalment(db, instalment_id)
    student = inst.fee_plan.student
    authorize_student_access(db, user, student)
    state = instalment_state(inst)
    return {
        "instalment": state,
        "student": {
            "id": student.id,
            "name": student.name,
            "student_code": student.student_code,
            "program": student.program,
        },
        "fee_plan": student.fee_plan.name,
        "payable_now": state["balance"],
    }


@router.post("/initiate")
def initiate(
    payload: PaymentInitiateRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict:
    """Step 1: create a PENDING payment intent (the confirmation screen).

    No money is considered received at this point.
    """
    inst = _load_instalment(db, payload.instalment_id)
    student = inst.fee_plan.student
    authorize_student_access(db, user, student)
    payment = initiate_payment(db, inst, payload.amount, payload.idempotency_key)
    return {
        "payment": payment_out(payment),
        "requires_confirmation": payment.status == "pending",
        "message": "Payment initiated. Confirm to complete." if payment.status == "pending"
                   else "This payment was already processed.",
    }


@router.post("/confirm")
def confirm(
    payload: PaymentConfirmRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict:
    """Step 2: backend confirms and records the transaction, then updates the ledger
    and cancels reminders for the instalment if it is now fully paid."""
    payment = db.get(Payment, payload.payment_id)
    if not payment:
        raise HTTPException(status_code=404, detail="Payment not found")
    student = db.get(Student, payment.student_id)
    authorize_student_access(db, user, student)

    if payload.idempotency_key and payload.idempotency_key != payment.idempotency_key:
        raise HTTPException(status_code=400, detail="Idempotency key mismatch")

    already = payment.status == "confirmed"
    payment = confirm_payment(db, payment)
    return {
        "payment": payment_out(payment),
        "receipt_no": payment.receipt_no,
        "duplicate": already,
        "message": "Payment already confirmed (no duplicate created)." if already
                   else "Payment confirmed and receipt generated.",
    }


@router.get("/{payment_id}/receipt")
def receipt(
    payment_id: int,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict:
    payment = db.get(Payment, payment_id)
    if not payment:
        raise HTTPException(status_code=404, detail="Payment not found")
    student = db.get(Student, payment.student_id)
    authorize_student_access(db, user, student)
    if payment.status != "confirmed":
        raise HTTPException(status_code=400, detail="Receipt available only for confirmed payments")

    inst = payment.instalment
    return {
        "receipt_no": payment.receipt_no,
        "issued_at": payment.confirmed_at,
        "amount": payment.amount,
        "method": payment.method,
        "student": {
            "name": student.name,
            "student_code": student.student_code,
            "program": student.program,
            "batch": student.batch,
            "centre": student.centre,
        },
        "instalment": {"label": inst.label, "due_date": inst.due_date},
        "fee_plan": student.fee_plan.name,
        "note": "Simulated payment receipt generated by FeeFlow (assessment demo).",
    }
